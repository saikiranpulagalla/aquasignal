from __future__ import annotations

from dataclasses import asdict

from signallock.benchmark.challenge_cases import INDEPENDENT_CLEAN_CASES, INDEPENDENT_UNSAFE_CASES
from signallock.benchmark.metrics import BenchmarkCaseResult, compute_metrics
from signallock.contracts.provenance import validate_provenance
from signallock.benchmark.mutations import (
    FaultClass,
    clean_paraphrase,
    inject_action_change,
    inject_action_removed,
    inject_audience_change,
    inject_exception_removed,
    inject_location_change,
    inject_negation_flip,
    inject_quantity_change,
    inject_time_change,
)
from signallock.contracts.extractor import HeuristicExtractor
from signallock.verification.engine import VerificationEngine


BASE_ALERTS = [
    "Residents in the eastern river district must shelter indoors until 6 PM. Do not enter the eastern underpass. Avoid roads with more than 30 cm of water, except emergency personnel.",
    "Residents in the western flood zone should shelter indoors until 7 PM. Do not use the western tunnel. Avoid water deeper than 40 cm, except emergency personnel.",
    "Residents in the north storm area must stay indoors until 8 PM. Do not cross the north bridge. Avoid roads with more than 20 cm of water, except emergency personnel.",
    "Residents in the south river district should shelter indoors until 5 PM. Do not drive through the south tunnel. Avoid water deeper than 25 cm, except emergency personnel.",
    "Residents in the eastern flood zone must shelter indoors until 9 PM. Do not enter the eastern tunnel. Avoid roads with more than 35 cm of water, except emergency personnel.",
    "Residents in the western river district should stay indoors until 10 PM. Do not use the western underpass. Avoid water deeper than 45 cm, except emergency personnel.",
    "Residents in the north flood zone must shelter indoors until 4 PM. Do not cross the north bridge. Avoid roads with more than 15 cm of water, except emergency personnel.",
    "Residents in the south storm area should shelter indoors until 11 PM. Do not enter the south underpass. Avoid water deeper than 50 cm, except emergency personnel.",
]

_MUTATORS = [
    inject_action_removed,
    inject_action_change,
    inject_negation_flip,
    inject_location_change,
    inject_quantity_change,
    inject_time_change,
    inject_audience_change,
    inject_exception_removed,
]



def run_demo_benchmark() -> dict:
    extractor = HeuristicExtractor()
    verifier = VerificationEngine()
    rows: list[BenchmarkCaseResult] = []
    detail: list[dict] = []

    for idx, source_text in enumerate(BASE_ALERTS, start=1):
        source = extractor.extract(source_text, source_id=f"base-{idx}")
        provenance_errors = validate_provenance(source_text, source)
        if provenance_errors:
            raise AssertionError(f"Invalid source provenance for base-{idx}: {provenance_errors}")

        # One controlled clean paraphrase per base alert.
        clean = clean_paraphrase(source_text)
        clean_contract = extractor.extract(clean.text, source_id=f"base-{idx}-clean")
        clean_result = verifier.verify(source, clean_contract)
        clean_case = BenchmarkCaseResult(
            case_id=f"base-{idx}-clean",
            fault=FaultClass.CLEAN.value,
            unsafe=False,
            decision=clean_result.decision.value,
            caught=clean_result.decision.value != "BLOCK",
        )
        rows.append(clean_case)
        detail.append({**asdict(clean_case), "source": source_text, "candidate": clean.text})

        for mutator in _MUTATORS:
            mutation = mutator(source_text)
            if mutation.text == source_text:
                continue
            candidate = extractor.extract(mutation.text, source_id=f"base-{idx}-{mutation.fault.value}")
            result = verifier.verify(source, candidate)
            case = BenchmarkCaseResult(
                case_id=f"base-{idx}-{mutation.fault.value}",
                fault=mutation.fault.value,
                unsafe=True,
                decision=result.decision.value,
                caught=result.decision.value in {"BLOCK", "REVIEW"},
            )
            rows.append(case)
            detail.append({
                **asdict(case),
                "source": source_text,
                "candidate": mutation.text,
                "critical_failures": result.critical_failures,
            })


    # Independently authored challenge set: not generated by the mutation regexes above.
    for case_id, source_text, candidate_text, note in INDEPENDENT_UNSAFE_CASES:
        try:
            source = extractor.extract(source_text, source_id=case_id + "-source")
            candidate = extractor.extract(candidate_text, source_id=case_id + "-candidate")
            result = verifier.verify(source, candidate)
            decision = result.decision.value
            failures = result.critical_failures
        except Exception as exc:
            # Extraction/schema failure is fail-closed: intercepted for human review, never PASS.
            decision = "REVIEW"
            failures = [f"extraction_error:{type(exc).__name__}"]
        row = BenchmarkCaseResult(case_id=case_id, fault=note, unsafe=True, decision=decision, caught=decision != "PASS")
        rows.append(row)
        detail.append({**asdict(row), "source": source_text, "candidate": candidate_text, "critical_failures": failures, "suite": "independent"})

    for case_id, source_text, candidate_text in INDEPENDENT_CLEAN_CASES:
        try:
            source = extractor.extract(source_text, source_id=case_id + "-source")
            candidate = extractor.extract(candidate_text, source_id=case_id + "-candidate")
            result = verifier.verify(source, candidate)
            decision = result.decision.value
        except Exception:
            decision = "REVIEW"
        row = BenchmarkCaseResult(case_id=case_id, fault="CLEAN_INDEPENDENT", unsafe=False, decision=decision, caught=decision != "BLOCK")
        rows.append(row)
        detail.append({**asdict(row), "source": source_text, "candidate": candidate_text, "suite": "independent"})

    metrics = compute_metrics(rows)
    return {"metrics": metrics.to_dict(), "cases": detail}
